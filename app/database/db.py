import sqlite3
from datetime import date, timedelta
from flask import g, current_app
from werkzeug.security import generate_password_hash

def is_postgres():
    """Check whether PostgreSQL is configured."""
    return bool(current_app.config.get("DATABASE_URL"))

class DatabaseConnection:
    """Keep database execution compatible across SQLite and PostgreSQL."""
    def __init__(self, connection, postgres=False):
        self.connection = connection
        self.postgres = postgres

    def execute(self, sql, args=()):
        if self.postgres:
            sql = sql.replace("?", "%s")
        return self.connection.execute(sql, args)

    def executemany(self, sql, args):
        if self.postgres:
            sql = sql.replace("?", "%s")
        return self.connection.executemany(sql, args)

    def __getattr__(self, name):
        return getattr(self.connection, name)

def db():
    """Get one database connection for the current request."""
    if "db" not in g:
        if is_postgres():
            import psycopg
            from psycopg.rows import dict_row

            connection = psycopg.connect(
                current_app.config["DATABASE_URL"],
                row_factory=dict_row
            )
            g.db = DatabaseConnection(
                connection,
                postgres=True
            )

        else:
            connection = sqlite3.connect(
                current_app.config["DATABASE"]
            )

            connection.row_factory = sqlite3.Row
            g.db = DatabaseConnection(connection)

    return g.db


def close_db(error=None):
    """Close the database connection after each request."""
    connection = g.pop("db", None)
    if connection is not None:
        connection.close()

def q(sql, args=(), one=False):
    """Execute a SELECT query."""
    rows = db().execute(sql, args).fetchall()
    if one:
        return rows[0] if rows else None
    return rows

def run(sql, args=()):
    """Execute INSERT, UPDATE or DELETE queries."""
    connection = db()
    connection.execute(sql, args)
    connection.commit()

def init_db():
    """Initialize the configured database."""
    if is_postgres():
        init_postgres()
    else:
        init_sqlite()

def init_sqlite():
    """Initialize the SQLite database."""
    connection = sqlite3.connect(
        current_app.config["DATABASE"]
    )
    try:
        connection.executescript(
            """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER PRIMARY KEY,
                username TEXT UNIQUE,
                full_name TEXT,
                password_hash TEXT,
                role TEXT
            );

            CREATE TABLE IF NOT EXISTS courses (
                id INTEGER PRIMARY KEY,
                code TEXT,
                name TEXT,
                lecturer_id INTEGER
            );

            CREATE TABLE IF NOT EXISTS enrollments (
                student_id INTEGER,
                course_id INTEGER,
                UNIQUE(student_id, course_id)
            );

            CREATE TABLE IF NOT EXISTS attendance (
                course_id INTEGER,
                student_id INTEGER,
                date TEXT,
                present INTEGER,
                UNIQUE(course_id, student_id, date)
            );

            CREATE TABLE IF NOT EXISTS audit_logs (
                id INTEGER PRIMARY KEY AUTOINCREMENT,
                user_id INTEGER,
                username TEXT,
                full_name TEXT,
                role TEXT,
                action TEXT NOT NULL,
                entity_type TEXT,
                entity_id INTEGER,
                details TEXT,
                created_at TEXT DEFAULT CURRENT_TIMESTAMP
            );

            CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at
            ON audit_logs(created_at);
            """
        )
        seed_demo_data(connection)
        connection.commit()
    finally:
        connection.close()

def init_postgres():
    import psycopg
    """Initialize the PostgreSQL database."""
    with psycopg.connect(
        current_app.config["DATABASE_URL"]
    ) as connection:
        schema = [
            """
            CREATE TABLE IF NOT EXISTS users (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                username TEXT UNIQUE,
                full_name TEXT,
                password_hash TEXT,
                role TEXT
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS courses (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                code TEXT,
                name TEXT,
                lecturer_id INTEGER
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS enrollments (
                student_id INTEGER,
                course_id INTEGER,
                UNIQUE(student_id, course_id)
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS attendance (
                course_id INTEGER,
                student_id INTEGER,
                date TEXT,
                present INTEGER,
                UNIQUE(course_id, student_id, date)
            )
            """,
            """
            CREATE TABLE IF NOT EXISTS audit_logs (
                id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                user_id INTEGER,
                username TEXT,
                full_name TEXT,
                role TEXT,
                action TEXT NOT NULL,
                entity_type TEXT,
                entity_id INTEGER,
                details TEXT,
                created_at TEXT DEFAULT ((CURRENT_TIMESTAMP AT TIME ZONE 'UTC')::text)
            )
            """,
            """
            CREATE INDEX IF NOT EXISTS idx_audit_logs_created_at
            ON audit_logs(created_at)
            """
        ]
        for statement in schema:
            connection.execute(statement)

        # Demo data is only inserted when the database is empty.
        if not connection.execute(
            "SELECT 1 FROM users LIMIT 1"
        ).fetchone():
            # Production account creation will be handled separately.
            pass

